package org.stackanvil.packetforge.generator;

import static com.github.javaparser.ast.Modifier.Keyword.FINAL;
import static com.github.javaparser.ast.Modifier.Keyword.PRIVATE;
import static com.github.javaparser.ast.Modifier.Keyword.PUBLIC;
import static com.github.javaparser.ast.Modifier.Keyword.STATIC;

import com.github.javaparser.JavaParser;
import com.github.javaparser.ParseProblemException;
import com.github.javaparser.ParseResult;
import com.github.javaparser.ParserConfiguration;
import com.github.javaparser.ast.CompilationUnit;
import com.github.javaparser.ast.Node;
import com.github.javaparser.ast.NodeList;
import com.github.javaparser.ast.body.CompactConstructorDeclaration;
import com.github.javaparser.ast.body.MethodDeclaration;
import com.github.javaparser.ast.body.RecordDeclaration;
import com.github.javaparser.ast.body.VariableDeclarator;
import com.github.javaparser.ast.expr.Expression;
import com.github.javaparser.ast.expr.MethodCallExpr;
import com.github.javaparser.ast.expr.NameExpr;
import com.github.javaparser.ast.expr.ObjectCreationExpr;
import com.github.javaparser.ast.expr.ThisExpr;
import com.github.javaparser.ast.expr.VariableDeclarationExpr;
import com.github.javaparser.ast.stmt.BlockStmt;
import com.github.javaparser.ast.stmt.ReturnStmt;
import com.github.javaparser.ast.type.ClassOrInterfaceType;
import com.github.javaparser.ast.type.Type;
import java.io.IOException;
import org.stackanvil.packetforge.generator.Analyzer.Model;

/** Builds model declarations and codec methods without mixing Java structure with file output. */
final class ModelJavaEmitter {
    private final JavaParser parser =
            new JavaParser(new ParserConfiguration().setLanguageLevel(ParserConfiguration.LanguageLevel.BLEEDING_EDGE));

    String emit(Model model) throws IOException {
        String fullName = model.generatedName();
        String simple = fullName.substring(fullName.lastIndexOf('.') + 1);
        var unit = new CompilationUnit(fullName.substring(0, fullName.lastIndexOf('.')));
        unit.setLineComment(" Generated by PacketForge. Regenerate instead of editing.");
        try {
            if (!model.constants().isEmpty()) {
                var declaration = unit.addEnum(simple, PUBLIC);
                model.constants().forEach(declaration::addEnumConstant);
            } else {
                unit.addImport("io.netty.buffer.ByteBuf");
                unit.addImport("org.stackanvil.packetforge.commons", false, true);
                unit.addType(record(model, simple));
            }
            return unit.toString();
        } catch (ParseProblemException failure) {
            throw new IOException("Cannot emit generated Java " + fullName, failure);
        }
    }

    private RecordDeclaration record(Model model, String simple) {
        var declaration = new RecordDeclaration().setName(simple).setPublic(true);
        for (var field : model.fields())
            declaration.addParameter(type(field.read().type()), field.name());
        if (model.packet()) declaration.addImplementedType("Packet");
        if (!model.validations().isEmpty()) {
            declaration.addMember(new CompactConstructorDeclaration(simple)
                    .setPublic(true)
                    .setBody(block(String.join("\n", model.validations()))));
        }
        if (model.program() == null) addFieldCodecs(declaration, model);
        declaration.addFieldWithInitializer(codecType(simple), "CODEC", codec(model, simple), PUBLIC, STATIC, FINAL);
        if (model.program() != null) {
            for (String helper : model.program().helpers())
                declaration.addMember(parsed(parser.parseBodyDeclaration(helper)));
        }
        if (model.packet()) {
            declaration
                    .addMethod("serialize", PUBLIC)
                    .setType("void")
                    .addMarkerAnnotation("Override")
                    .addParameter("ByteBuf", "output")
                    .setBody(new BlockStmt()
                            .addStatement(call("CODEC", "encode")
                                    .addArgument("output")
                                    .addArgument(new ThisExpr())));
        }
        return declaration;
    }

    private void addFieldCodecs(RecordDeclaration declaration, Model model) {
        for (int i = 0; i < model.fields().size(); i++) {
            var field = model.fields().get(i);
            declaration.addFieldWithInitializer(
                    codecType(Analyzer.boxed(field.read().type())),
                    "READ_" + i,
                    expression(field.read().codec()),
                    PRIVATE,
                    STATIC,
                    FINAL);
            Expression writer = field.write().codec().equals(field.read().codec())
                    ? new NameExpr("READ_" + i)
                    : expression(field.write().codec());
            declaration.addFieldWithInitializer(
                    codecType(Analyzer.boxed(field.write().type())), "WRITE_" + i, writer, PRIVATE, STATIC, FINAL);
        }
    }

    private Expression codec(Model model, String simple) {
        var codec = new ObjectCreationExpr()
                .setType(type("PacketCodec<>").asClassOrInterfaceType())
                .setAnonymousClassBody(new NodeList<>());
        codec.addAnonymousClassBody(new MethodDeclaration()
                .setName("decode")
                .setPublic(true)
                .setType(type(simple))
                .addParameter("ByteBuf", "input")
                .setBody(decode(model, simple)));
        codec.addAnonymousClassBody(new MethodDeclaration()
                .setName("encode")
                .setPublic(true)
                .setType("void")
                .addParameter("ByteBuf", "output")
                .addParameter(type(simple), "value")
                .setBody(encode(model)));
        return model.decodeFailure().isEmpty()
                ? codec
                : call("WireCodecs", "skipDecodeFailures").addArgument(codec);
    }

    private BlockStmt decode(Model model, String simple) {
        if (model.program() != null) return block(model.program().decode());
        var body = new BlockStmt();
        var arguments = new NodeList<Expression>();
        for (int i = 0; i < model.fields().size(); i++) {
            var field = model.fields().get(i);
            String local = "$field_" + field.name();
            body.addStatement(new VariableDeclarationExpr(new VariableDeclarator(
                    type(field.read().type()),
                    local,
                    call("READ_" + i, "decode").addArgument("input"))));
            arguments.add(new NameExpr(local));
        }
        return body.addStatement(
                new ReturnStmt(new ObjectCreationExpr(null, new ClassOrInterfaceType(null, simple), arguments)));
    }

    private BlockStmt encode(Model model) {
        if (model.program() != null) return block(model.program().encode());
        var body = new BlockStmt();
        for (int i = 0; i < model.fields().size(); i++) {
            body.addStatement(call("WRITE_" + i, "encode")
                    .addArgument("output")
                    .addArgument(call("value", model.fields().get(i).name())));
        }
        return body;
    }

    private Type codecType(String valueType) {
        return type("PacketCodec<" + valueType + ">");
    }

    private Type type(String source) {
        return parsed(parser.parseType(source));
    }

    private Expression expression(String source) {
        return parsed(parser.parseExpression(source));
    }

    private BlockStmt block(String source) {
        return parsed(parser.parseBlock("{" + source + "}"));
    }

    private static MethodCallExpr call(String owner, String method) {
        return new MethodCallExpr(new NameExpr(owner), method);
    }

    private static <T extends Node> T parsed(ParseResult<T> result) {
        if (!result.isSuccessful()) throw new ParseProblemException(result.getProblems());
        return result.getResult().orElseThrow();
    }
}
