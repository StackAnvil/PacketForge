package org.stackanvil.packetforge.generator;

import static com.github.javaparser.ast.Modifier.Keyword.FINAL;
import static com.github.javaparser.ast.Modifier.Keyword.PUBLIC;
import static com.github.javaparser.ast.Modifier.Keyword.STATIC;

import com.github.javaparser.JavaParser;
import com.github.javaparser.ParseProblemException;
import com.github.javaparser.ParseResult;
import com.github.javaparser.ParserConfiguration;
import com.github.javaparser.ast.CompilationUnit;
import com.github.javaparser.ast.Node;
import com.github.javaparser.ast.stmt.BlockStmt;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.Locale;
import org.stackanvil.packetforge.generator.Analyzer.Dispatch;
import org.stackanvil.packetforge.generator.SourceIndex.Unsupported;

/** Emits typed component constants directly from the recovered registry cases. */
final class ComponentTypesEmitter {
    static final String NAME = "org.stackanvil.packetforge.protocol.DataComponentTypes";
    private final JavaParser parser =
            new JavaParser(new ParserConfiguration().setLanguageLevel(ParserConfiguration.LanguageLevel.BLEEDING_EDGE));

    String emit(Dispatch table) {
        var unit = new CompilationUnit("org.stackanvil.packetforge.protocol");
        unit.setLineComment(" Generated by PacketForge. Regenerate instead of editing.");
        unit.addImport("java.util.List");
        unit.addImport("net.kyori.adventure.key.Key");
        unit.addImport("org.stackanvil.packetforge.commons", false, true);
        var declaration = unit.addClass("DataComponentTypes", PUBLIC, FINAL);
        declaration
                .addConstructor(com.github.javaparser.ast.Modifier.Keyword.PRIVATE)
                .setBody(new BlockStmt());
        var names = new ArrayList<String>();
        var unique = new HashSet<String>();
        for (var branch : table.cases()) {
            String name = constant(branch.name());
            if (!unique.add(name)) throw new Unsupported("Component names collide in Java: " + branch.name());
            names.add(name);
            declaration.addFieldWithInitializer(
                    parsed(parser.parseType(
                            "DataComponentType<" + Analyzer.boxed(branch.value().type()) + ">")),
                    name,
                    parsed(parser.parseExpression("new DataComponentType<>("
                            + branch.key() + ", Key.key(\"" + branch.name()
                            + "\"), WireCodecs.lazy(() -> " + branch.value().codec() + "))")),
                    PUBLIC,
                    STATIC,
                    FINAL);
        }
        declaration.addMember(
                parsed(parser.parseBodyDeclaration("public static List<DataComponentType<?>> values() { return List.of("
                        + String.join(", ", names) + "); }")));
        declaration.addMember(parsed(parser.parseBodyDeclaration("""
                public static DataComponentType<?> byId(int id) {
                    for (var type : values()) if (type.id() == id) return type;
                    throw new IllegalArgumentException("Unknown component ID: " + id);
                }
                """)));
        declaration.addMember(parsed(parser.parseBodyDeclaration("""
                public static DataComponentType<?> byKey(Key key) {
                    for (var type : values()) if (type.key().equals(key)) return type;
                    throw new IllegalArgumentException("Unknown component key: " + key);
                }
                """)));
        return unit.toString();
    }

    private static String constant(String key) {
        String name = key.startsWith("minecraft:") ? key.substring("minecraft:".length()) : key;
        name = name.replaceAll("[^a-z0-9_]", "_").toUpperCase(Locale.ROOT);
        if (name.isEmpty()) throw new Unsupported("Empty component key");
        return Character.isJavaIdentifierStart(name.charAt(0)) ? name : "_" + name;
    }

    private static <T extends Node> T parsed(ParseResult<T> result) {
        if (!result.isSuccessful()) throw new ParseProblemException(result.getProblems());
        return result.getResult().orElseThrow();
    }
}
